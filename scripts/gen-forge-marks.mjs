#!/usr/bin/env node
/**
 * Generates the packaged Forge marks from the one source of brand geometry.
 *
 * The mark is the Forge F ("crossbar break"): a voxel F on a six-module grid with
 * one crossbar module knocked out. Geometry is read straight out of
 * src/webview/src/components/forge/marks.ts, which the webview's ForgeMark and
 * ForgeWordmark also draw from, so the packaged icons can never drift from the UI.
 *
 * Every output puts each module on whole pixels of its native size, so the F is
 * sharp where VS Code shows it:
 *   resources/forge-logo.svg        24px activity bar icon. currentColor: VS Code
 *                                   masks activity-bar icons to the theme colour,
 *                                   so a baked fill would be thrown away. No ghost
 *                                   module -- at 24px monochrome it reads as noise.
 *   resources/forge-logo-brand.svg  16px editor tab icon, brand purple, with the
 *                                   ghost module (an <img> has no currentColor).
 *   resources/forge-logo.png        128x128 extension icon, brand purple.
 *
 * Usage: node scripts/gen-forge-marks.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src', 'webview', 'src', 'components', 'forge', 'marks.ts');
const RES = join(ROOT, 'resources');

/** Brand purple. Must match --pajamas-brand-purple-02p in forge-pajamas.css. */
const BRAND = [0x77, 0x59, 0xc2];
const TOKEN = '--pajamas-brand-purple-02p';

// ---------------------------------------------------------------- geometry ---
const source = readFileSync(SRC, 'utf8');
const readNumber = (name) => {
  const m = source.match(new RegExp(`export const ${name}\\s*=\\s*([\\d.]+)`));
  if (!m) throw new Error(`Could not read ${name} from marks.ts`);
  return Number(m[1]);
};
const readRects = (block) =>
  [...block.matchAll(/\[\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\s*\]/g)].map((m) => m.slice(1, 5).map(Number));

const MODULES = readNumber('F_MODULES');
const GHOST_OPACITY = readNumber('F_GHOST_OPACITY');
const solidBlock = source.match(/export const F_SOLID[^=]*=\s*\[([\s\S]*?)\];/)?.[1];
const ghostBlock = source.match(/export const F_GHOST\b[^=]*=\s*(\[[^\]]*\])/)?.[1];
if (!solidBlock || !ghostBlock) throw new Error('Could not read F geometry from marks.ts');
const SOLID = readRects(solidBlock);
const [GHOST] = readRects(ghostBlock);
if (SOLID.length === 0 || !GHOST) throw new Error('marks.ts F geometry is empty');

// Guard the brand value against the generated palette, so recolouring the brand
// in one place cannot silently leave the packaged icons behind.
const palette = readFileSync(join(ROOT, 'src', 'webview', 'src', 'styles', 'forge-pajamas.css'), 'utf8');
const expected = palette.match(new RegExp(`${TOKEN}:\\s*(#[0-9a-fA-F]{6})`))?.[1];
const brandHex = '#' + BRAND.map((c) => c.toString(16).padStart(2, '0')).join('');
if (expected?.toLowerCase() !== brandHex) {
  throw new Error(`Brand drift: ${TOKEN} is ${expected}, but this script paints ${brandHex}.`);
}

// --------------------------------------------------------------------- SVG ---
/** An SVG of `size` px with the F at `unit` px per module, centred. */
const svg = ({ size, unit, fill, ghost }) => {
  const offset = (size - MODULES * unit) / 2;
  const rect = ([x, y, w, h], extra = '') =>
    `  <rect x="${offset + x * unit}" y="${offset + y * unit}" width="${w * unit}" height="${h * unit}"${extra}/>\n`;
  return (
    `<!-- GENERATED by scripts/gen-forge-marks.mjs -- do not edit by hand. -->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}" ` +
    `fill="${fill}" shape-rendering="crispEdges">\n` +
    SOLID.map((r) => rect(r)).join('') +
    (ghost ? rect(GHOST, ` opacity="${GHOST_OPACITY}"`) : '') +
    `</svg>\n`
  );
};

writeFileSync(join(RES, 'forge-logo.svg'), svg({ size: 24, unit: 3, fill: 'currentColor', ghost: false }));
writeFileSync(join(RES, 'forge-logo-brand.svg'), svg({ size: 16, unit: 2, fill: brandHex, ghost: true }));

// --------------------------------------------------------------------- PNG ---
const SIZE = 128;
const UNIT = 18; // 6 modules x 18px = 108px, leaving 10px of breathing room
const OFFSET = (SIZE - MODULES * UNIT) / 2;

const raw = Buffer.alloc(SIZE * (SIZE * 4 + 1));
const paint = ([x, y, w, h], alpha) => {
  for (let py = OFFSET + y * UNIT; py < OFFSET + (y + h) * UNIT; py++) {
    for (let px = OFFSET + x * UNIT; px < OFFSET + (x + w) * UNIT; px++) {
      const o = py * (SIZE * 4 + 1) + 1 + px * 4;
      raw[o] = BRAND[0];
      raw[o + 1] = BRAND[1];
      raw[o + 2] = BRAND[2];
      raw[o + 3] = Math.round(alpha * 255);
    }
  }
};
SOLID.forEach((r) => paint(r, 1));
paint(GHOST, GHOST_OPACITY);

const CRC_TABLE = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c;
  }
  return t;
})();
const crc32 = (buf) => {
  let c = -1;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
};
const chunk = (type, data) => {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
};

const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(SIZE, 0);
ihdr.writeUInt32BE(SIZE, 4);
ihdr[8] = 8; // bit depth
ihdr[9] = 6; // colour type: RGBA
writeFileSync(join(RES, 'forge-logo.png'), Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk('IHDR', ihdr),
  chunk('IDAT', deflateSync(raw, { level: 9 })),
  chunk('IEND', Buffer.alloc(0)),
]));

console.log(
  `forge marks: F (${SOLID.length} modules + ghost) -> forge-logo.svg (24px, currentColor), ` +
  `forge-logo-brand.svg (16px, ${brandHex}), forge-logo.png (${SIZE}x${SIZE})`,
);
