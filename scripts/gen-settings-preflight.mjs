#!/usr/bin/env node
/**
 * Generate a copy of Tailwind's preflight that applies only inside Forge's own
 * Settings page.
 *
 * Why this exists. The official Claude Code webview has no CSS reset: its
 * elements sit on the browser defaults plus VS Code's host stylesheet, so text
 * rows are `line-height: normal`, boxes are `content-box`, <svg> is inline and
 * <button> keeps its native padding -- and every official rule was written
 * against that. Tailwind's preflight changes all four globally, which made
 * every ported surface measurably wrong at once (the header 44px tall instead of
 * 28px, the composer footer 37px instead of 26px). So Forge no longer loads
 * preflight for the document.
 *
 * The Settings page is Forge's own (it has no official twin) and was built on
 * preflight's assumptions, so it keeps them -- inside an @scope, where they
 * cannot reach the official surfaces.
 *
 * Usage: node scripts/gen-settings-preflight.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const tw = dirname(require.resolve('tailwindcss/package.json'));
const version = require('tailwindcss/package.json').version;
const SCOPE_ROOT = '.cursor-settings-pane-outer-wrapper';
const OUT = 'src/webview/src/styles/forge-settings-preflight.css';

let css = readFileSync(join(tw, 'preflight.css'), 'utf8');

// Inside @scope, `html` is outside the subtree; the page root plays its part.
css = css.replace(/html,\s*:host\s*\{/, ':scope {');

// Forge never takes a system typeface (see forge-fonts.css), so preflight's
// font stacks are dropped; the page inherits the bundled faces from <body>.
css = css.replace(/^\s*font-family:\s*--theme\([\s\S]*?\);\s*(\/\*.*?\*\/)?\s*$/gm, '');

const indented = css.split('\n').map((l) => (l ? `  ${l}` : l)).join('\n');
writeFileSync(OUT, `/*!
 * GENERATED by scripts/gen-settings-preflight.mjs from tailwindcss@${version}
 * preflight.css -- do not edit by hand. Scoped to Forge's Settings page only;
 * see the script for why the rest of the webview must not have a reset.
 */
@scope (${SCOPE_ROOT}) {
${indented}
}
`);
console.log(`gen-settings-preflight: tailwindcss@${version} preflight -> ${OUT} (scoped to ${SCOPE_ROOT})`);
